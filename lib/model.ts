// Token Radar, model radar-2.
//
// One sealed snapshot in, one ranked board out. The board ranks the
// watchlist and every rankable pre-token protocol below the watchlist floor:
// the watchlist is the floor, the early radar is everything rankable below
// it, and the live-token protocols are kept apart with their market caps.
// A protocol above the floor that the watchlist leaves out is left out on
// purpose: above the floor the watchlist is the gate, because the protocols
// it leaves out there are the wrapped, staked and bridged products of
// tokens that already trade, not launches of their own.
//
// Implied value is one function of the snapshot's own figures only:
//
//   base     = tvl_usd x 0.22
//   growth   = clamp(change_7d, -60, 120), weight 0.8
//   maturity = 0.55 + min(age_days, 1460) / 1460 x 0.45
//   breadth  = 1 + 0.02 x min(chains - 1, 3), capped at 1.06
//   bleed    = 0.92 when change_7d is below -25, otherwise 1
//   implied  = max(1, round(base x growth x maturity x breadth x bleed))
//
// Why these five inputs, and nothing else:
// - TVL is the size of the bet: a protocol holding billions has more to
//   tokenise than one holding millions.
// - Seven-day growth is momentum: a protocol still growing after years
//   with no token is a stronger launch candidate than one shrinking.
// - Age with no token is patience: the longer a protocol has run at scale
//   without issuing a token, the larger the token it has left to issue.
// - Chain count is breadth: a protocol live on several chains is less
//   exposed to one chain's fortunes than a single-chain one.
// - The bleed guard is honesty about decline: a protocol losing more than
//   a quarter of its TVL in a week is not the same bet as a flat one, even
//   at the same size.
// No protocol name is ever special-cased. The same function scores every
// row, and the dashboard recomputes each row from the same figures so the
// page and board.json always agree.

export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

export interface ModelConstants {
  base_multiple: number;
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  bleed_below: number;
  bleed_factor: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
  chain_step: number;
  chain_max_bonus: number;
}

export const MODEL: ModelConstants = {
  base_multiple: 0.22,
  growth_weight: 0.8,
  growth_floor: -60,
  growth_cap: 120,
  bleed_below: -25,
  bleed_factor: 0.92,
  maturity_floor: 0.55,
  maturity_range: 0.45,
  maturity_days: 1460,
  unknown_age_days: 365,
  chain_step: 0.02,
  chain_max_bonus: 0.06,
};

export const MODEL_VERSION = 'radar-2';

